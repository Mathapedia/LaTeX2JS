import LaTeX2JS from '../src';
const latex = new LaTeX2JS();

describe('class test', () => {
  it('Environments', () => {
    expect(latex.Environments).toEqual([
      'pspicture',
      'verbatim',
      'enumerate',
      'print',
      'nicebox',
      'itemize',
      'description',
    ]);
  });
  it('Delimiters', () => {
    expect(latex.Delimiters).toEqual({
      description: { begin: /\\begin\{description\}/, end: /\\end\{description\}/ },
      enumerate: { begin: /\\begin\{enumerate\}/, end: /\\end\{enumerate\}/ },
      itemize: { begin: /\\begin\{itemize\}/, end: /\\end\{itemize\}/ },
      nicebox: { begin: /\\begin\{nicebox\}/, end: /\\end\{nicebox\}/ },
      print: { begin: /\\begin\{print\}/, end: /\\end\{print\}/ },
      pspicture: { begin: /\\begin\{pspicture\}/, end: /\\end\{pspicture\}/ },
      verbatim: { begin: /\\begin\{verbatim\}/, end: /\\end\{verbatim\}/ },
    });
  });
  it('Ignore', () => {
    expect(latex.Ignore).toEqual([
      /^\%/,
      /\\begin\{document\}/,
      /\\end\{document\}/,
      /\\begin\{interactive\}/,
      /\\end\{interactive\}/,
      /\\usepackage/,
      /\\documentclass/,
      /\\tableofcontents/,
      /\\author/,
      /\\date/,
      /\\maketitle/,
      /\\title/,
      /\\pagestyle/,
      /\\smallskip/,
      /\\medskip/,
      /\\bigskip/,
      /\\nobreak/,
      /\\begin\{center\}/,
      /\\end\{center\}/,
    ]);
  });
  it('Text', () => {
    expect(latex.Text).toBeDefined();
    expect(latex.Text.Functions).toBeDefined();
    expect(latex.Text.Expressions).toBeDefined();
    expect(Object.keys(latex.Text.Functions).sort()).toEqual([
      'LaTeX',
      'TeX',
      'bf',
      'cite',
      'closeq',
      'emph',
      'euler',
      'footnote',
      'href',
      'hrule',
      'hspace',
      'img',
      'it',
      'mdash',
      'ndash',
      'newpage',
      'noindent',
      'openq',
      'overline',
      'paragraph',
      'rm',
      'rule',
      'section',
      'set',
      'sl',
      'subsection',
      'subsubsection',
      'textbf',
      'textcolor',
      'textit',
      'textrm',
      'textsc',
      'texttt',
      'tt',
      'underline',
      'vspace',
      'youtube',
    ]);
    expect(Object.keys(latex.Text.Expressions).sort()).toEqual([
      'LaTeX',
      'TeX',
      'bf',
      'cite',
      'closeq',
      'emph',
      'euler',
      'footnote',
      'href',
      'hrule',
      'hspace',
      'img',
      'it',
      'mdash',
      'ndash',
      'newpage',
      'noindent',
      'openq',
      'overline',
      'paragraph',
      'rm',
      'rule',
      'section',
      'set',
      'sl',
      'subsection',
      'subsubsection',
      'textbf',
      'textcolor',
      'textit',
      'textrm',
      'textsc',
      'texttt',
      'tt',
      'underline',
      'vspace',
      'youtube',
    ]);
  });
  it('Headers', () => {
    expect(latex.Headers).toBeDefined();
    expect(latex.Headers.Functions).toBeDefined();
    expect(latex.Headers.Expressions).toBeDefined();
    expect(Object.keys(latex.Headers.Functions).sort()).toEqual([
      'axiom',
      'bq',
      'claim',
      'corollary',
      'definition',
      'endaxiom',
      'endclaim',
      'endcorollary',
      'enddefinition',
      'endexample',
      'endexercise',
      'endlemma',
      'endnote',
      'endproblem',
      'endproposition',
      'endquestion',
      'endremark',
      'endsolution',
      'endtheorem',
      'eq',
      'example',
      'exercise',
      'lemma',
      'note',
      'problem',
      'proof',
      'proposition',
      'qed',
      'question',
      'remark',
      'solution',
      'theorem',
    ]);
    expect(Object.keys(latex.Headers.Expressions).sort()).toEqual([
      'axiom',
      'bq',
      'claim',
      'corollary',
      'definition',
      'endaxiom',
      'endclaim',
      'endcorollary',
      'enddefinition',
      'endexample',
      'endexercise',
      'endlemma',
      'endnote',
      'endproblem',
      'endproposition',
      'endquestion',
      'endremark',
      'endsolution',
      'endtheorem',
      'eq',
      'example',
      'exercise',
      'lemma',
      'note',
      'problem',
      'proof',
      'proposition',
      'qed',
      'question',
      'remark',
      'solution',
      'theorem',
    ]);
  });
});
